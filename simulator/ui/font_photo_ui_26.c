/**
 * font_photo_ui_26.c —— 照片表盘的中文占位文案字体（26 px / 4 bpp / Noto Sans SC）
 *
 * ## 为什么需要一份新字体
 *
 * 设计稿（`docs/photo-wireless-design.md` §9.4）要求照片表盘的占位文案是中文：
 *   无照片   →「还没有照片 · 在 App 里添加」
 *   无存储卡 →「未检测到存储卡」
 *   接收中   →「接收 62%」
 *
 * 项目里唯一的 CJK 字体 `date_cjk_26`（`font_date_cjk_26.c`）**只**包含日期用字形
 * （`0123456789月日星期一二三四五六 ·`），没有这些字；而 LVGL 8.4 **没有字体回退**
 * （v9 才有），缺字会直接显示成方块。所以按需生成一份只含**必需字形**的字体，
 * 与其它 `font_*.c` 一样单独放（`tools/sync_firmware.sh` 的 `font_*.c` 通配已覆盖，
 * 模拟器 Makefile 也是 `ui/*.c` 全量编译，两侧都不用改构建脚本）。
 *
 * ## 生成命令（lv_font_conv 1.5.3，逐字节可复现）
 *
 *   node lv_font_conv.js --size 26 --bpp 4 --format lvgl \
 *     --font design/assets/fonts/src/NotoSansSC-Regular.ttf \
 *     --symbols "还没有照片·在里添加未检测到存储卡接收 Ap0123456789%" \
 *     --no-compress --lv-include lvgl.h --lv-font-name photo_ui_26 \
 *     -o simulator/ui/font_photo_ui_26.c
 *
 * 字表 = 还没有照片·在里添加未检测到存储卡接收 + ` Ap0123456789%`
 * （ASCII 那串是给「在 App 里添加」「接收 62%」用的）。
 * 需要新文案时**只改 --symbols 重新生成**，不要手改下面的位图。
 *
 * ⚠️ 使用方：`ui_photo.c`（`LV_FONT_DECLARE(photo_ui_26);`）。
 */

